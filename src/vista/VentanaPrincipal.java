    private void btnFiltrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFiltrarActionPerformed
        // TODO add your handling code here:
        try{
            java.util.Date fechaInicio = dcFechaInicio.getDate();
            java.util.Date fechaFin = dcFechaFin.getDate();
            
            if(fechaInicio == null || fechaFin == null){
                JOptionPane.showMessageDialog(this, "Debes seleccionar la fecha de inicio y la fecha de fin para filtrar ",
                                                    "Error de filtrado ", JOptionPane.WARNING_MESSAGE);
                return;
            }
            
            modelo.AlquilerDAO dao = new modelo.AlquilerDAO();
            tablaAlquileres.setModel(dao.obtenerAlquileres(fechaInicio, fechaFin ));
        }catch (Exception e){
            JOptionPane.showMessageDialog(this, "Error al procesar el filtro: " + e.getMessage(), "Error interno ", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnFiltrarActionPerformed

